"""Upwind SBP order 6 operators"""

import numpy as np

m = 20
h=1


H = np.diag(np.ones(m))
H[0:6, 0:6] = np.array([[0.13613e5 / 0.43200e5, 0, 0, 0, 0, 0],
                        [0, 0.12049e5 / 0.8640e4, 0, 0, 0, 0],
                        [0, 0, 0.535e3 / 0.864e3, 0, 0, 0],
                        [0, 0, 0, 0.1079e4 / 0.864e3, 0, 0],
                        [0, 0, 0, 0, 0.7841e4 / 0.8640e4, 0],
                        [0, 0, 0, 0, 0, 0.43837e5 / 0.43200e5]])
H[m-6:m, m-6:m] = np.fliplr(np.flipud(H[0:6, 0:6]))
H = H * h
HI = np.linalg.inv(H)

Qp = (1/30 * np.diag(np.ones(m-2), -2) - 2/5 * np.diag(np.ones(m-1), -1) -
      7/12 * np.diag(np.ones(m), 0) + 4/3 * np.diag(np.ones(m-1), 1) -
      1/2 * np.diag(np.ones(m-2), 2) + 2/15 * np.diag(np.ones(m-3), 3) -
      1/60 * np.diag(np.ones(m-4), 4))

Q_U = np.array([[-0.265e3 / 0.128688e6, 0.1146190567e10 / 0.1737288000e10, -0.1596619e7 / 0.18384000e8, -0.55265831e8 / 0.579096000e9, 0.26269819e8 / 0.3474576000e10, 0.2464501e7 / 0.144774000e9],
                [-0.1116490567e10 / 0.1737288000e10, -0.8839e4 / 0.214480e6, 0.190538869e9 / 0.347457600e9, 0.102705469e9 / 0.694915200e9, 0.413741e6 / 0.9651600e7, -0.191689861e9 / 0.3474576000e10],
                [0.1096619e7 / 0.18384000e8, -0.135385429e9 / 0.347457600e9, -0.61067e5 / 0.321720e6, 0.45137333e8 / 0.57909600e8, -0.253641811e9 / 0.694915200e9, 0.70665929e8 / 0.579096000e9],
                [0.66965831e8 / 0.579096000e9, -0.208765789e9 / 0.694915200e9, -0.17623253e8 / 0.57909600e8, -0.18269e5 / 0.45960e5, 0.410905829e9 / 0.347457600e9, -0.477953317e9 / 0.1158192000e10],
                [-0.49219819e8 / 0.3474576000e10, 0.293299e6 / 0.9651600e7, 0.26422771e8 / 0.694915200e9, -0.141938309e9 / 0.347457600e9, -0.346583e6 / 0.643440e6, 0.2217185207e10 / 0.1737288000e10],
                [-0.2374501e7 / 0.144774000e9, 0.142906261e9 / 0.3474576000e10, -0.3137129e7 / 0.579096000e9, -0.29884283e8 / 0.1158192000e10, -0.630168407e9 / 0.1737288000e10, -0.3559e4 / 0.6128e4]])

Qp[0:6, 0:6] = Q_U
Qp[m-6:m, m-6:m] = np.flipud(np.fliplr(Q_U[0:6, 0:6])).T

Qm = -Qp.T

e_1 = np.zeros(m)
e_1[0] = 1
e_m = np.zeros(m)
e_m[m-1] = 1

Dp = HI.dot(Qp - 1/2 * np.outer(e_1, e_1) + 1/2 * np.outer(e_m, e_m))
Dm = HI.dot(Qm - 1/2 * np.outer(e_1, e_1) + 1/2 * np.outer(e_m, e_m))
print(H*Dp + H*Dm.T)
